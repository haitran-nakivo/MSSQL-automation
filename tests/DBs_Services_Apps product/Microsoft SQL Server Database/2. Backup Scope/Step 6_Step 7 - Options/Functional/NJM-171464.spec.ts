import { test, expect } from '../../../../../../fixtures';
import { RUN_OPTIONS } from '../../../../../../fixtures/run-options';
import { BkA7OptionsFlows } from '../../../../../../flows/bkA7-options.flows';
import { BkA7RecoverFlows } from '../../../../../../flows/bkA7-recover.flows';
import { backupJobName } from '../../../../../../helpers/backup-env';
import { readA7Setup } from '../../../../../../helpers/bkA7-env';

// NJM-171464: "Backup - Step 6/Step 7 - Options - Run job with all options".
// Env (.env, owner-supplied): NAKIVO_BK_INSTANCE_ITEM, NAKIVO_BK_INSTANCE_DB_SIMPLE, NAKIVO_BK_REPO_PRIMARY.
// Side effects: creates job NJM-171464 and a saved encryption password with Description NJM-171464 (generated by the test). afterEach deletes the job with its backups, then the password.
// case-vs-ui: Options is Step 4 of the 4-step wizard. In the UI Backup encryption Enabled greys out Network acceleration (Observed, see ENC-06 / NJM-191229), so "all options together"
//   cannot hold: the spec sets Job priority 1, Network encryption Enabled and Backup encryption Enabled, and asserts that Network acceleration becomes unavailable when Backup encryption is
//   enabled instead of enabling all four. A job with Network acceleration Enabled and Backup encryption Enabled cannot be created through the UI. Status PARTIAL.
test.use(RUN_OPTIONS);

const KEY = 'NJM-171464';
let jobCreated = false;
let passwordCreated = false;

test.afterEach(async ({ page, backupFlows }) => {
  const flows = new BkA7OptionsFlows(page, backupFlows);
  if (jobCreated) {
    try {
      await backupFlows.discardJobIfPresent(backupJobName(KEY), false);
    } catch {
      // best effort
    }
    jobCreated = false;
  }
  if (passwordCreated) {
    try {
      await flows.cleanupPasswords(readA7Setup(), KEY);
    } catch {
      // best effort
    }
    passwordCreated = false;
  }
});

test(
  'NAKIVO runs a database backup with job priority, network encryption and backup encryption set together',
  { tag: '@NJM-171464' },
  async ({ signedIn: _s, page, backupFlows }, testInfo) => {
    test.setTimeout(900_000);
    const setup = readA7Setup();
    const flows = new BkA7OptionsFlows(page, backupFlows);
    const recover = new BkA7RecoverFlows(page, backupFlows);
    const name = backupJobName(KEY);
    const password = `Nj${Date.now()}-Aa1!y`;
    testInfo.annotations.push({ type: 'case-vs-ui', description: 'Network acceleration and Backup encryption are mutually exclusive in the UI; all four cannot be enabled together.' });

    await test.step('1. Precondition: open the Backup for Database wizard', async () => {
      await backupFlows.openWizard();
      await expect(backupFlows.wizard.title).toBeVisible();
    });

    await test.step('2. Advance to the Options step', async () => {
      await flows.advanceToOptions(setup, name);
      await expect(flows.ui.optionLabel('Backup encryption')).toBeVisible();
    });

    await test.step('3. Set Job priority, Network encryption and Backup encryption together (Network acceleration is excluded by Backup encryption)', async () => {
      await flows.pickOption('Job priority', '1');
      await flows.pickOption('Network encryption', 'Enabled');
      await flows.enableBackupEncryption();
      expect(await flows.comboValue('Backup encryption')).toBe('Enabled');
      // case-vs-ui: enabling Backup encryption greys out Network acceleration.
      expect(await flows.isDisabled(backupFlows.wizard.optionInput('Network acceleration')), 'Network acceleration is still editable with Backup encryption enabled').toBe(true);
      await flows.openSetPassword();
      passwordCreated = true;
      expect(await flows.createPassword({ password, description: KEY })).toBe(true);
      expect(await flows.comboValue('Job priority')).toBe('1');
      expect(await flows.comboValue('Network encryption')).toBe('Enabled');
    });

    await test.step('4. Finish creating the job and run it on demand: the job runs to completion', async () => {
      const warned = await flows.finishAndRun();
      jobCreated = true;
      testInfo.annotations.push({ type: 'observed-outcome', description: `Key Management Service warning shown on Finish & Run: ${warned}` });
      await backupFlows.jobs.statusLine.waitFor({ timeout: 60_000 });
      expect(await backupFlows.waitForResult(600_000)).toBe('successful');
    });

    await test.step('5. Verify all options took effect and the recovery point exists', async () => {
      expect(await flows.recoverEnabled(), 'Recover is disabled: no recovery point was created').toBe(true);
      const options = await flows.readJobOptionsText();
      testInfo.annotations.push({ type: 'observed-outcome', description: `Job options popup: ${options}` });
      expect(options).toMatch(/network encryption/i);
      const row = await recover.repositoryBackupRowText(setup.repo, name);
      testInfo.annotations.push({ type: 'observed-outcome', description: `Repository Backups row: "${row}"` });
      expect(row).toMatch(/encrypt|enabled|yes|\bon\b|aes/i);
    });
  },
);
