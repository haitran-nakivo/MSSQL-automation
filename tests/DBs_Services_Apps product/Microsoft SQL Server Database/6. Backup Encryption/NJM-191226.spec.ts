import { test, expect } from '../../../../fixtures';
import { RUN_OPTIONS } from '../../../../fixtures/run-options';
import { BkA7OptionsFlows } from '../../../../flows/bkA7-options.flows';
import { BkA7RecoverFlows } from '../../../../flows/bkA7-recover.flows';
import { backupJobName } from '../../../../helpers/backup-env';
import { readA7Setup } from '../../../../helpers/bkA7-env';

// NJM-191226: "ENC-04 - Encrypted backup job runs successfully end-to-end".
// Env (.env, owner-supplied): NAKIVO_BK_INSTANCE_ITEM, NAKIVO_BK_INSTANCE_DB_SIMPLE, NAKIVO_BK_REPO_PRIMARY.
// Side effects: creates job NJM-191226 and a saved password with Description "NJM-191226 <timestamp>" (the password is generated by the test). afterEach deletes the job with its backups and then the password.
// case-vs-ui: the dialog locators and the Recover wizard are UNVERIFIED (pages/bkA7-options.page.ts, pages/bkA7-recover.page.ts). "Run details / job log report backup encryption enabled" is checked through the
//   saved "Job options" text (the notes show no other encryption line in the log). "Recovery point reported as encrypted" is read from the Encryption column of the repository Backups row (UNVERIFIED cell text).
//   The Recover wizard is only opened and cancelled here (inspection, no recovery is started). Status PARTIAL.
test.use(RUN_OPTIONS);

const KEY = 'NJM-191226';
let jobCreated = false;
let passwordCreated = false;

test.afterEach(async ({ page, backupFlows }) => {
  const flows = new BkA7OptionsFlows(page, backupFlows);
  if (jobCreated) {
    try {
      await backupFlows.discardJobIfPresent(backupJobName(KEY), false);
    } catch {
      // best effort
    }
    jobCreated = false;
  }
  if (passwordCreated) {
    try {
      await flows.cleanupPasswords(readA7Setup(), KEY);
    } catch {
      // best effort
    }
    passwordCreated = false;
  }
});

test(
  'NAKIVO creates, runs and reports an encrypted database backup job end to end',
  { tag: '@NJM-191226' },
  async ({ signedIn: _s, page, backupFlows }, testInfo) => {
    test.setTimeout(900_000);
    const setup = readA7Setup();
    const flows = new BkA7OptionsFlows(page, backupFlows);
    const recover = new BkA7RecoverFlows(page, backupFlows);
    const name = backupJobName(KEY);
    const description = `${KEY} ${Date.now()}`;
    const password = `Nj${Date.now()}-Aa1!z`;

    await test.step('1. Create a new backup job: any source, any repository, default schedule (on demand here), reach 4. Options', async () => {
      await flows.openOptionsStep(setup, name);
      await expect(flows.ui.optionLabel('Backup encryption')).toBeVisible();
    });

    await test.step('2. Backup encryption = Enabled > settings > Create password: same password twice, a recognizable Description, Proceed: the dialog closes and Backup encryption shows Enabled', async () => {
      await flows.enableBackupEncryption();
      await flows.openSetPassword();
      passwordCreated = true;
      expect(await flows.createPassword({ password, description }), 'the Set a password dialog did not close after Proceed').toBe(true);
      expect(await flows.comboValue('Backup encryption')).toBe('Enabled');
    });

    await test.step('3. Give the job a recognizable name (already set) and Finish & Run', async () => {
      const warned = await flows.finishAndRun();
      jobCreated = true;
      testInfo.annotations.push({ type: 'observed-outcome', description: `Key Management Service warning shown on Finish & Run: ${warned}` });
      await expect(backupFlows.jobs.statusLine).toBeVisible({ timeout: 60_000 });
    });

    await test.step('4. Monitor the job until it completes: Successful, no encryption-related warning or alarm', async () => {
      expect(await backupFlows.waitForResult(600_000)).toBe('successful');
      const warnings = await flows.pageTextsMatching(/encrypt.*(warning|alarm|fail|error)|(warning|alarm|fail|error).*encrypt/i);
      expect(warnings, 'an encryption related warning or alarm is shown').toEqual([]);
    });

    await test.step('5. Open the run details and the job log: backup encryption is reported and the password never appears in plaintext', async () => {
      const options = await flows.readJobOptionsText();
      testInfo.annotations.push({ type: 'observed-outcome', description: `Job options popup: ${options}` });
      expect(options).toMatch(/encrypt/i);
      const pageText = (await backupFlows.visibleTexts()).join('\n');
      expect(pageText + options, 'the password is shown in plaintext').not.toContain(password);
    });

    await test.step('6. Reopen the job > 4. Options > settings > Manage passwords: the password is listed with the description and its value is masked', async () => {
      await flows.openEditOptions(name);
      expect(await flows.comboValue('Backup encryption')).toBe('Enabled');
      await flows.openSetPassword();
      await flows.openManagePasswords();
      const rows = await flows.managePasswordRowTexts();
      expect(rows.some((r) => r.includes(description)), `no Manage passwords row carries "${description}"`).toBe(true);
      expect(rows.join('\n'), 'the password value is shown in plaintext').not.toContain(password);
      await flows.closeManagePasswords();
      await flows.ui.cancelButton().click({ timeout: 10_000 });
      await flows.leaveWizard();
    });

    await test.step('7. Data Protection > Recover: inspect the recovery point created by this job (reported as encrypted)', async () => {
      await backupFlows.openJob(name);
      const opened = await recover.openRecover();
      testInfo.annotations.push({ type: 'observed-outcome', description: `Recover wizard opened: ${opened} (UNVERIFIED locators)` });
      if (opened) await recover.cancelWizard();
      const row = await recover.repositoryBackupRowText(setup.repo, name);
      testInfo.annotations.push({ type: 'observed-outcome', description: `Repository Backups row: "${row}"` });
      expect(row, 'the backup of the job is not listed in the repository').not.toBe('');
      expect(row).toMatch(/encrypt|enabled|yes|\bon\b|aes/i);
    });
  },
);
