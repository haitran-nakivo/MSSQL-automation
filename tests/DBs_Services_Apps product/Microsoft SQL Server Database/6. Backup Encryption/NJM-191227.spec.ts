import { test, expect } from '../../../../fixtures';
import { RUN_OPTIONS } from '../../../../fixtures/run-options';
import { BkA7OptionsFlows } from '../../../../flows/bkA7-options.flows';
import { BkA7RecoverFlows } from '../../../../flows/bkA7-recover.flows';
import { backupJobName, readBackupDatabase } from '../../../../helpers/backup-env';
import { readA7Setup } from '../../../../helpers/bkA7-env';

// NJM-191227: "ENC-05 - Reuse a saved password via Select password".
// Env (.env, owner-supplied): NAKIVO_BK_INSTANCE_ITEM, NAKIVO_BK_INSTANCE_DB_SIMPLE (source of the job that saves the password), NAKIVO_BK_INSTANCE_DB_FULL (a different source for the job that
//   reuses it, as the case asks), NAKIVO_BK_REPO_PRIMARY.
// Side effects: creates jobs NJM-191227-seed (saved, never run: it only creates the saved password) and NJM-191227 (runs once), and one saved password with Description "NJM-191227 <timestamp>" (generated by
//   the test). afterEach deletes both jobs with their backups, then the password.
// case-vs-ui: the case's precondition ("at least one saved password; if none, Manage passwords > Add Password") is met by saving the first job with a new password (Create password); the Add Password
//   dialog is not used. All dialog locators and the repository Encryption cell are UNVERIFIED. Status IMPLEMENTED (locators UNVERIFIED).
test.use(RUN_OPTIONS);

const KEY = 'NJM-191227';
const created: string[] = [];
let passwordCreated = false;

test.afterEach(async ({ page, backupFlows }) => {
  const flows = new BkA7OptionsFlows(page, backupFlows);
  for (const name of created) {
    try {
      await backupFlows.discardJobIfPresent(name, false);
    } catch {
      // best effort
    }
  }
  created.length = 0;
  if (passwordCreated) {
    try {
      await flows.cleanupPasswords(readA7Setup(), KEY);
    } catch {
      // best effort
    }
    passwordCreated = false;
  }
});

test(
  'NAKIVO lets a new job reuse a saved encryption password through Select password and encrypts the backup with it',
  { tag: '@NJM-191227' },
  async ({ signedIn: _s, page, backupFlows }, testInfo) => {
    test.setTimeout(1_200_000);
    const first = readA7Setup();
    const second = { ...first, db: readBackupDatabase('INSTANCE', 'FULL') };
    const flows = new BkA7OptionsFlows(page, backupFlows);
    const recover = new BkA7RecoverFlows(page, backupFlows);
    const seed = backupJobName(KEY, '-seed');
    const name = backupJobName(KEY);
    const description = `${KEY} ${Date.now()}`;
    const password = `Nj${Date.now()}-Aa1!s`;

    await test.step('Precondition: a saved encryption password exists (created through a first job that is saved, not run)', async () => {
      await flows.openOptionsStep(first, seed);
      await flows.enableBackupEncryption();
      await flows.openSetPassword();
      passwordCreated = true;
      expect(await flows.createPassword({ password, description })).toBe(true);
      await backupFlows.wizard.finishButton.click({ timeout: 10_000 });
      created.push(seed);
      await expect(backupFlows.jobs.statusLine).toBeVisible({ timeout: 60_000 });
    });

    await test.step('1. Create a new backup job (a different source) with any repository and reach 4. Options', async () => {
      await flows.openOptionsStep(second, name);
      await expect(flows.ui.optionLabel('Backup encryption')).toBeVisible();
    });

    await test.step('2. Backup encryption = Enabled > settings', async () => {
      await flows.enableBackupEncryption();
      await flows.openSetPassword();
      await expect(flows.ui.setPasswordDialog()).toBeVisible();
    });

    await test.step('3. Select the Select password radio: it and its dropdown are enabled', async () => {
      await flows.ui.selectPasswordRadio().click({ timeout: 10_000 });
      expect(await flows.isChecked(flows.ui.selectPasswordRadio())).toBe(true);
      expect(await flows.isDisabled(flows.ui.selectPasswordCombo())).toBe(false);
    });

    await test.step('4. Open the dropdown: saved passwords are listed by description only; choose ours and Proceed (password fields are not required)', async () => {
      await flows.ui.selectPasswordCombo().click({ timeout: 10_000 });
      const items = await flows.page.locator('.x-boundlist-item:visible').allInnerTexts();
      expect(items.some((t) => t.includes(description)), `the saved password "${description}" is not listed`).toBe(true);
      expect(items.join('\n'), 'the password value is listed').not.toContain(password);
      await flows.page.keyboard.press('Escape');
      expect(await flows.selectSavedPassword(description), 'Proceed did not close the dialog after a selection').toBe(true);
      expect(await flows.comboValue('Backup encryption')).toBe('Enabled');
    });

    await test.step('5. Name the job (already set) and Finish & Run: the job completes Successful', async () => {
      await flows.finishAndRun();
      created.push(name);
      await expect(backupFlows.jobs.statusLine).toBeVisible({ timeout: 60_000 });
      expect(await backupFlows.waitForResult(600_000)).toBe('successful');
    });

    await test.step('6. Reopen Manage passwords: no duplicate entry was created', async () => {
      await flows.openEditOptions(name);
      await flows.openSetPassword();
      await flows.openManagePasswords();
      const rows = (await flows.managePasswordRowTexts()).filter((r) => r.includes(KEY));
      expect(rows.length, 'the saved password was duplicated or lost').toBe(1);
      await flows.closeManagePasswords();
      await flows.ui.cancelButton().click({ timeout: 10_000 });
      await flows.leaveWizard();
    });

    await test.step('7. Verify the recovery point in the target repository: it is encrypted', async () => {
      const row = await recover.repositoryBackupRowText(first.repo, name);
      testInfo.annotations.push({ type: 'observed-outcome', description: `Repository Backups row: "${row}"` });
      expect(row).not.toBe('');
      expect(row).toMatch(/encrypt|enabled|yes|\bon\b|aes/i);
    });
  },
);
