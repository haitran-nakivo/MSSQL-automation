import { test, expect } from '../../../../fixtures';
import { RUN_OPTIONS } from '../../../../fixtures/run-options';
import { BkA7OptionsFlows } from '../../../../flows/bkA7-options.flows';
import { backupJobName } from '../../../../helpers/backup-env';
import { readA7Setup } from '../../../../helpers/bkA7-env';

// NJM-191229: "ENC-06 - Mutual exclusivity with Network acceleration".
// Env (.env, owner-supplied): NAKIVO_BK_INSTANCE_ITEM, NAKIVO_BK_INSTANCE_DB_SIMPLE, NAKIVO_BK_REPO_PRIMARY.
// Side effects: creates job NJM-191229 and a saved password with Description "NJM-191229 <timestamp>" (generated by the test); runs the job once in its final state. afterEach deletes the job (with backups) and the password.
// case-vs-ui: the case sets Network acceleration = Enabled first and then Backup encryption = Enabled. The notes show a saved job with acceleration and network encryption Enabled having Backup encryption greyed,
//   so if the second pick is refused because the row is already greyed, step 2 fails and that is the finding. Dialog locators UNVERIFIED. The value Network acceleration shows while greyed is attached as
//   observed-outcome (the case accepts "reset or clearly marked as not applied").
test.use(RUN_OPTIONS);

const KEY = 'NJM-191229';
let jobCreated = false;
let passwordCreated = false;

test.afterEach(async ({ page, backupFlows }) => {
  const flows = new BkA7OptionsFlows(page, backupFlows);
  try {
    await flows.leaveWizard();
  } catch {
    // best effort
  }
  if (jobCreated) {
    try {
      await backupFlows.discardJobIfPresent(backupJobName(KEY), false);
    } catch {
      // best effort
    }
    jobCreated = false;
  }
  if (passwordCreated) {
    try {
      await flows.cleanupPasswords(readA7Setup(), KEY);
    } catch {
      // best effort
    }
    passwordCreated = false;
  }
});

test(
  'NAKIVO makes Backup encryption and Network acceleration mutually exclusive and keeps that state after saving',
  { tag: '@NJM-191229' },
  async ({ signedIn: _s, page, backupFlows }, testInfo) => {
    test.setTimeout(1_200_000);
    const setup = readA7Setup();
    const flows = new BkA7OptionsFlows(page, backupFlows);
    const name = backupJobName(KEY);
    const accel = () => backupFlows.wizard.optionInput('Network acceleration');
    const password = `Nj${Date.now()}-Aa1!m`;
    const description = `${KEY} ${Date.now()}`;

    await test.step('Precondition: a new job at 4. Options', async () => {
      await flows.openOptionsStep(setup, name);
      await expect(flows.ui.optionLabel('Network acceleration')).toBeVisible();
    });

    await test.step('1. Set Network acceleration = Enabled', async () => {
      await flows.pickOption('Network acceleration', 'Enabled');
      expect(await flows.comboValue('Network acceleration')).toBe('Enabled');
    });

    await test.step('2. Set Backup encryption = Enabled: Network acceleration is greyed out and its previous value is reset or marked as not applied', async () => {
      await flows.enableBackupEncryption();
      expect(await flows.comboValue('Backup encryption')).toBe('Enabled');
      expect(await flows.isDisabled(accel()), 'Network acceleration is still editable').toBe(true);
      testInfo.annotations.push({ type: 'observed-outcome', description: `Network acceleration shows "${await flows.comboValue('Network acceleration')}" while greyed out` });
    });

    await test.step('3. Set Backup encryption back to Disabled: Network acceleration is editable again with a valid value', async () => {
      await flows.pickOption('Backup encryption', 'Disabled');
      expect(await flows.isDisabled(accel())).toBe(false);
      expect(['Enabled', 'Disabled']).toContain(await flows.comboValue('Network acceleration'));
    });

    await test.step('4. Set Backup encryption = Enabled again and create a valid password, Proceed', async () => {
      await flows.enableBackupEncryption();
      await flows.openSetPassword();
      passwordCreated = true;
      expect(await flows.createPassword({ password, description })).toBe(true);
    });

    await test.step('5. Name the job (already set) and Finish', async () => {
      await backupFlows.wizard.finishButton.click({ timeout: 10_000 });
      jobCreated = true;
      await expect(backupFlows.jobs.statusLine).toBeVisible({ timeout: 60_000 });
    });

    await test.step('6. Reopen the job > 4. Options: Backup encryption is Enabled, Network acceleration is disabled, no silent re-enable', async () => {
      await flows.openEditOptions(name);
      expect(await flows.comboValue('Backup encryption')).toBe('Enabled');
      expect(await flows.isDisabled(accel())).toBe(true);
      expect(await flows.comboValue('Network acceleration'), 'Network acceleration was silently re-enabled').not.toBe('Enabled');
    });

    await test.step('7. Set Backup encryption = Disabled and Save; reopen: Network acceleration is editable again and its change saves cleanly', async () => {
      await flows.pickOption('Backup encryption', 'Disabled');
      expect(await flows.isDisabled(accel())).toBe(false);
      await flows.pickOption('Network acceleration', 'Enabled');
      await flows.saveEdit();
      await flows.openEditOptions(name);
      expect(await flows.comboValue('Backup encryption')).toBe('Disabled');
      expect(await flows.comboValue('Network acceleration')).toBe('Enabled');
      expect(await flows.isDisabled(accel())).toBe(false);
      await flows.leaveWizard();
    });

    await test.step('8. Run the job once in this final state: it completes Successful', async () => {
      await backupFlows.openJob(name);
      await backupFlows.runOpenJob();
      expect(await backupFlows.waitForResult(600_000)).toBe('successful');
    });
  },
);
